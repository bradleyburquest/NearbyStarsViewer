function buildWikipediaArticleUrl(title: string | undefined): string | null {
  return title
    ? `https://en.wikipedia.org/wiki/${encodeURIComponent(title.replaceAll(' ', '_'))}`
    : null;
}

export function getWikipediaArticleUrl(name: string): string | null {
  return buildWikipediaArticleUrl(wikipediaArticleTitles[name]);
}

export function getSystemWikipediaArticleUrl(name: string): string | null {
  return buildWikipediaArticleUrl(systemWikipediaArticleTitles[name]);
}
